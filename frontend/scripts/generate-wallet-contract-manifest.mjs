#!/usr/bin/env node
// frontend/scripts/generate-wallet-contract-manifest.mjs
// VF Wallet Task 10, Part A1 (owner-directed fix for the VF Wallet Task 9 reviewer finding).
//
// PROBLEM this replaces: WalletShell.test.jsx's old drift guard (CONTRACT_PORTED_RULES) was a
// HAND-TRANSCRIBED list of ~25 selectors, each with a hand-typed expected CSS block. That shape
// can only ever re-check rules a human already remembered to add to the list -- it structurally
// cannot notice a 26th contract rule that should have been ported but never got added to the list
// at all. That exact blind spot is how two whole rules (the global form-control font-family rule,
// `color-scheme: dark`) shipped missing through two review passes.
//
// FIX (reviewer's prescription): a MANIFEST of "wallet-relevant" contract selectors, GENERATED by
// parsing the actual contract CSS text (not retyped by hand), committed to the repo (the contract
// itself is gitignored -- see below), and re-derived by running this script whenever the contract
// changes. WalletShell.test.jsx then asserts every manifest entry has a shipped counterpart --
// so a contract rule that matches the wallet-relevant selection rule below and is never ported
// fails the build the next time someone regenerates the manifest and runs the guard, MUCH more
// automatically than a human remembering to add a 26th line to a hand list.
//
// WHAT COUNTS AS "GENERATED, NOT TRANSCRIBED": the SELECTION of which selectors matter (the
// WALLET_SCOPE_PATTERN / SHARED_PRIMITIVE_SELECTORS below) is still an authored judgment call --
// exactly like the `name` column of the old hand list, or contractTokens.test.js's own documented
// tradeoff (its token VALUES are hand-pinned because the contract is gitignored and unavailable in
// CI). What changes is that the manifest's CONTENT (which properties a matched rule declares, in
// which media context) is extracted mechanically from the contract text by parseCss() below, never
// retyped -- eliminating the transcription-typo/omission failure mode this task was asked to close.
// Any FUTURE rule whose selector already carries the `.pc-wallet` scope (the convention every
// wallet-specific contract rule already follows) is picked up automatically on the next
// regeneration with ZERO generator edits -- that is the "self-maintaining" part. Only a genuinely
// NEW shared/global primitive (not already scoped under `.pc-wallet`) needs a one-line addition to
// SHARED_PRIMITIVE_SELECTORS, same as the old hand list needed a one-line addition for a new
// `.pc-wallet-*` class -- except now that addition only names WHICH rule matters, never its VALUE.
//
// The contract file (docs/superpowers/specs/2026-07-23-pocket-crew-visual-contract.css) is
// local-only/gitignored and will not exist in a clean CI checkout (contractTokens.test.js documents
// the identical constraint) -- so this script must be run locally, against a local contract copy,
// whenever the contract changes, and its OUTPUT (the manifest JSON) is what gets committed and what
// CI actually reads.
//
// Usage:
//   node scripts/generate-wallet-contract-manifest.mjs [--contract=<path>] [--out=<path>]
// Defaults: contract = ../docs/superpowers/specs/2026-07-23-pocket-crew-visual-contract.css
// (relative to this repo's frontend/ directory), out = src/wallet/ui/walletContractManifest.generated.json

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const FRONTEND_ROOT = path.resolve(HERE, '..')
const DEFAULT_CONTRACT = path.resolve(
  FRONTEND_ROOT,
  '../docs/superpowers/specs/2026-07-23-pocket-crew-visual-contract.css'
)
const DEFAULT_OUT = path.resolve(
  FRONTEND_ROOT,
  'src/wallet/ui/walletContractManifest.generated.json'
)

export function normalizeWs(text) {
  return text.replace(/\s+/g, ' ').trim()
}

// Strip comments once, up front -- both /* */ blocks (the only comment style this CSS uses).
export function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, '')
}

// Minimal recursive-descent CSS block splitter. This file's CSS is hand-authored and simple (one
// `@layer` wrapper, `@media` blocks nested exactly one level, no rule-in-rule nesting otherwise) --
// a brace-depth walk is all that's needed; a full CSS-AST library would be scope creep for a
// single, structurally simple, already-known-good input file (ponytail: stdlib-shaped code over a
// new dependency for a five-rule-shape grammar).
// Returns a flat array of { selector, media, declarations: [{ prop, value }] }.
export function parseCss(text, media = null) {
  const src = stripComments(text)
  const rules = []
  let i = 0
  while (i < src.length) {
    const braceIdx = src.indexOf('{', i)
    if (braceIdx === -1) break
    const prelude = normalizeWs(src.slice(i, braceIdx))
    let depth = 1
    let j = braceIdx + 1
    while (depth > 0 && j < src.length) {
      if (src[j] === '{') depth++
      else if (src[j] === '}') depth--
      j++
    }
    const body = src.slice(braceIdx + 1, j - 1)
    if (/^@media\b/.test(prelude)) {
      const mediaQuery = normalizeWs(prelude.replace(/^@media\s*/, ''))
      rules.push(...parseCss(body, media ? `${media}, ${mediaQuery}` : mediaQuery))
    } else if (/^@layer\b/.test(prelude)) {
      // Unwrap -- @layer is a grouping-only construct for this file, not a selection boundary.
      rules.push(...parseCss(body, media))
    } else if (prelude && !prelude.startsWith('@')) {
      rules.push({ selector: prelude, media, declarations: parseDeclarations(body) })
    }
    // Any other at-rule (none present today) is silently skipped rather than mis-parsed.
    i = j
  }
  return rules
}

function parseDeclarations(body) {
  return body
    .split(';')
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const idx = d.indexOf(':')
      if (idx === -1) return null
      return {
        prop: normalizeWs(d.slice(0, idx)).toLowerCase(),
        value: normalizeValue(d.slice(idx + 1)),
      }
    })
    .filter(Boolean)
}

export function normalizeValue(value) {
  return normalizeWs(value)
    .replace(/\s*,\s*/g, ',')
    .replace(/['"]/g, '')
    .toLowerCase()
}

// Strips the `.pc-wallet` SCOPE class (used as a bare prefix: `.pc-wallet foo`, `.pc-wallet:where(..)`,
// `.pc-wallet, .pc-wallet foo`) without touching a distinct class that happens to start with the
// same text (`.pc-wallet-shell`, `.pc-wallet-critical`, ...) -- the lookahead requires the next
// character to end the token (whitespace, `:`, `,`, or end of string), never a `-`.
function stripWalletScope(selector) {
  return selector.replace(/\.pc-wallet(?=[\s:,]|$)/g, '')
}

function unwrapWhere(selector) {
  return selector.replace(/:where\(([^)]*)\)/g, '$1')
}

// The comma-separated "target" tokens a selector actually matches, once the wallet scope prefix
// and any `:where()` wrapper (both pure scoping/specificity devices, not new match targets) are
// removed. Used to compare a contract selector against WalletShell's shipped (often re-scoped)
// equivalent structurally, instead of requiring byte-identical selector text.
// A selector that IS the scope class alone (`.pc-wallet` itself, e.g. the component root rule, or
// the synthetic color-scheme entry mapped onto it) strips down to nothing -- fall back to the
// original (unstripped) text as the one token so `.pc-wallet` still compares equal to itself
// instead of two empty sets (which would never intersect, even when byte-identical).
export function selectorTokens(selector) {
  const stripped = unwrapWhere(stripWalletScope(selector))
    .split(',')
    .map((s) => normalizeWs(s))
    .filter(Boolean)
  return stripped.length > 0 ? stripped : [normalizeWs(selector)]
}

// Selectors that are wallet-relevant WITHOUT carrying `.pc-wallet` in their own text -- shared,
// global primitives a wallet screen depends on. Each entry is the contract's OWN normalized
// selector text. This list is the one place a genuinely NEW shared primitive needs a manual
// addition (naming it, never its value) -- see the file header.
const SHARED_PRIMITIVE_SELECTORS = new Set(
  [
    '*, *::before, *::after',
    'h1, h2, h3, button, input, select, textarea',
    'code, pre, .pc-technical',
    ':where(a, button, input, select, textarea, summary):focus-visible',
    '.pc-button',
    '.pc-button--primary',
    '.pc-button--secondary',
    '.pc-button:active:not(:disabled)',
    ".pc-button:disabled, .pc-button[aria-disabled='true']",
    '.pc-field',
    '.pc-field > label',
    '.pc-input',
    '.pc-field-help, .pc-field-error',
    '.pc-row',
    '.pc-row:last-child',
    '.pc-brand-lockup',
    '.pc-brand-lockup img, .pc-brand-lockup svg',
    '.pc-brand-lockup--compact img, .pc-brand-lockup--compact svg',
    '.pc-network-badge',
    // NOT '.pc-network-badge img, .pc-network-badge svg' (base or --compact, or the 767px
    // variant): WalletShell's network badge is TEXT-ONLY ("Stellar testnet", no icon element) --
    // confirmed by grepping the shipped source, not assumed. Requiring an image-sizing rule for an
    // icon this component never renders would be a false-positive trap, not a real omission (the
    // rejection checklist's item 9 forbids a logo WITHOUT text, not text without a logo). If a
    // future task adds an icon to this badge, add these selectors back here.
    '.pc-route-intro',
    ":where(button, [role='button'], a[href], summary, input, select, textarea)",
  ].map(normalizeWs)
)

// :root's mega token-block is out of scope (Foundation's contractTokens.test.js already guards
// token values) EXCEPT the one bare, non-token declaration living inside it that a wallet screen
// actually depends on: `color-scheme: dark`. Modeled as its own synthetic rule, remapped onto
// `.pc-wallet` (the selector WalletShell documents porting it onto, since this component owns no
// document-level `:root` of its own) -- a generator-level remapping rule, not a hand-picked value.
function rootColorSchemeEntry(rules) {
  const root = rules.find((r) => r.selector === normalizeWs(":root, :root[data-theme='forest']"))
  const decl = root?.declarations.find((d) => d.prop === 'color-scheme')
  if (!decl) return null
  return { selector: '.pc-wallet', media: null, declarations: [decl] }
}

// Selectors that DO carry `.pc-wallet` (so the generic predicate below would otherwise flag them)
// but are DELIBERATELY not ported, for a reasoned reason recorded in WalletShell.jsx's own header
// history -- not an oversight this guard should chase. `.pc-wallet-critical, [data-pocket-critical]`
// is the one case today: VF Wallet Task 9 fix loop 1 found the contract's paired
// `animation: none !important` rule for this selector is a NO-OP (the selector is element-scoped,
// not descendant-scoped, so it never stopped a child from animating) and removed it outright,
// documenting "keeping a rule that looks like a safety net but is not is worse than no rule." A
// manifest that forced this rule back in would be reverting a reasoned fix, not catching a bug.
const EXCLUDED_SELECTORS = new Set([normalizeWs('.pc-wallet-critical, [data-pocket-critical]')])

function isWalletRelevant(rule) {
  if (EXCLUDED_SELECTORS.has(rule.selector)) return false
  if (rule.selector.includes('.pc-wallet')) return true
  return SHARED_PRIMITIVE_SELECTORS.has(rule.selector)
}

// Builds the committed manifest from raw contract CSS text: a flat, generated (never hand-typed)
// list of { id, selector, media, tokens, properties } entries -- one per wallet-relevant contract
// rule (plus the synthetic color-scheme entry). `tokens` is the pre-computed selectorTokens() set,
// `properties` the declared property names (deduplicated) -- WalletShell.test.jsx uses both to
// check a shipped counterpart exists, without re-implementing this parsing.
export function buildManifest(contractText) {
  const rules = parseCss(contractText)
  const entries = []
  for (const rule of rules) {
    if (!isWalletRelevant(rule)) continue
    entries.push(rule)
  }
  const colorScheme = rootColorSchemeEntry(rules)
  if (colorScheme) entries.push(colorScheme)

  return entries.map((rule, index) => ({
    id: `${index}:${rule.selector}${rule.media ? ` @${rule.media}` : ''}`,
    selector: rule.selector,
    media: rule.media,
    tokens: selectorTokens(rule.selector),
    properties: [...new Set(rule.declarations.map((d) => d.prop))],
  }))
}

function parseArgs(argv) {
  const out = {}
  for (const arg of argv) {
    const m = arg.match(/^--([\w-]+)=(.*)$/)
    if (m) out[m[1]] = m[2]
  }
  return out
}

function main() {
  const args = parseArgs(process.argv.slice(2))
  const contractPath = args.contract ? path.resolve(process.cwd(), args.contract) : DEFAULT_CONTRACT
  const outPath = args.out ? path.resolve(process.cwd(), args.out) : DEFAULT_OUT

  let contractText
  try {
    contractText = readFileSync(contractPath, 'utf8')
  } catch (e) {
    console.error(`[generate-wallet-contract-manifest] cannot read contract at ${contractPath}`)
    console.error(
      '[generate-wallet-contract-manifest] the contract is gitignored/local-only -- run this ' +
        'against your local checkout, or pass --contract=<path>.'
    )
    process.exit(1)
  }

  const manifest = buildManifest(contractText)
  writeFileSync(outPath, JSON.stringify(manifest, null, 2) + '\n')
  console.log(`[generate-wallet-contract-manifest] wrote ${manifest.length} entries to ${outPath}`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main()
}
